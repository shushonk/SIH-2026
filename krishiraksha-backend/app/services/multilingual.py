def get_multilingual_advisory(disease: str, lang: str = "en") -> dict:
    """
    Returns localized text and IPM recommendations for a disease in English, Hindi, or Marathi.
    """
    lang = lang.lower() if lang else "en"
    if lang not in ["hi", "mr"]:
        lang = "en"

    # Default fallback to English if translation missing or lang is en
    if lang == "en" or disease not in TRANSLATION_STORE or lang not in TRANSLATION_STORE[disease]:
        return None  # Let caller use base English

    return TRANSLATION_STORE[disease][lang]
